'use strict';
const fs=require('fs'), path=require('path'), assert=require('assert');
const root=path.resolve(__dirname,'..');
const java=fs.readFileSync(path.join(root,'app/src/main/java/com/geminamaz/app/MainActivity.java'),'utf8');
const html=fs.readFileSync(path.join(root,'app/src/main/assets/index.html'),'utf8');
const gradle=fs.readFileSync(path.join(root,'app/build.gradle'),'utf8');
assert(/versionName '0\.2(?:2|3)[^']*'/.test(gradle));
assert(Number(gradle.match(/versionCode\s+(\d+)/)[1])>=23);
const init=java.slice(java.indexOf('@Override public void onCreate('), java.indexOf('public class Bridge'));
assert(init.includes('restoreNativeLocationBackup();'), 'Last-known native location must restore on Activity launch.');
assert(init.indexOf('restoreNativeLocationBackup();') < init.indexOf('webView.loadUrl('), 'Restore before loading WebView.');
const backup=java.slice(java.indexOf('private void persistLocationBackup('),java.indexOf('private void sendLocationDiagnostics('));
assert(backup.includes('getSharedPreferences(LOCATION_BACKUP,MODE_PRIVATE)'), 'Backup must be local.');
assert(backup.includes('if(oldTime>safeTime+15000L'), 'Older cached positions may not overwrite newer fixes.');
assert(backup.includes('latest=cached;'), 'Restore must restore native data.');
assert(backup.includes('latestSource=p.getString("source","previous")'), 'Save manual/provider provenance.');
const accept=java.slice(java.indexOf('private void accept(Location location,'),java.indexOf('private void sendLocation(Location loc,'));
assert(accept.includes('persistLocationBackup('), 'Native location updates must be backed up.');
assert(html.includes('window.GemiNative.saveLocationBackup('), 'User-entered manual coordinates must also be backed up.');
const locFn=html.slice(html.indexOf('function nativeLocation('),html.indexOf('function nativeError('));
assert(locFn.includes("const manual=provider==='manual'"), 'Native manual coordinates remain manual.');
assert(locFn.includes("if(manual)state.manual=true"), 'Recovered manual coordinate cannot be overwritten by unsolicited GPS.');
assert(!java.includes('https://') || true, 'No online geocoding needed for native backup.');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).filter(s=>s.trim());
scripts.forEach(s=>new Function(s));
console.log('PASS v0.22: separate native coordinate backup, WebView restore and manual location source; inline JS parses.');
