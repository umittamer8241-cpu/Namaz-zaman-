'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert');
const root=path.resolve(__dirname,'..'),assets=path.join(root,'app/src/main/assets');
const html=fs.readFileSync(path.join(assets,'index.html'),'utf8');
const css=fs.readFileSync(path.join(assets,'learning_styles.css'),'utf8');
const gradle=fs.readFileSync(path.join(root,'app/build.gradle'),'utf8');
assert(Number(gradle.match(/versionCode\s+(\d+)/)[1])>=24);
assert(html.includes('id="compass-arrow-mode"'));
assert(html.includes("oriented?wrap(bearing-h,360):bearing"),'North-up bearing must be used when sensor is unverified.');
assert(html.includes("needle.classList.toggle('compass-unreliable',hasLocation&&!oriented&&!byShadow&&!byManual)"));
assert(html.includes("needle.classList.toggle('compass-no-location',!hasLocation)"));
assert(html.includes('Kuzey üstte: bu sadece haritaya göre kıble açısıdır.'));
assert(html.includes('telefonu bu oka göre çevirmeyin'));
assert(html.includes('Şematik (sensör doğrulanmadı)'), 'Diagnostic must not claim invisible pointer.');
assert(css.includes('.needle-wrap.ornate-single-needle.compass-unreliable{'));
assert(css.includes('opacity:.84!important'), 'Schematic arrow must be visible, but subdued.');
assert(css.includes('.needle-wrap.ornate-single-needle.compass-no-location{'));
assert(css.includes('opacity:0!important'), 'Arrow must remain hidden without coordinates.');
assert(!css.includes('.needle-wrap.compass-unreliable{opacity:0'),'Unverified arrow must no longer vanish.');
const mode=html.match(/const COMPASS_ARROW_MODES=([\s\S]*?);\r?\nfunction compassArrowWords/);
assert(mode,'Localized mode dictionary missing.');
for(const lang of ['tr','en','ms','id','ar','ru','fr','de','es','pt','az','ur'])assert(mode[1].includes('\n '+lang+':['),'Mode missing for '+lang);
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).filter(s=>s.trim());
scripts.forEach(s=>new Function(s));
console.log('PASS v0.23: visible schematic bearing with explicit warning, verified live rotation, 12 locales, no-location hidden.');
