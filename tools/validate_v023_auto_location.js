'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const java=fs.readFileSync(path.join(root,'app/src/main/java/com/geminamaz/app/MainActivity.java'),'utf8');
const html=fs.readFileSync(path.join(root,'app/src/main/assets/index.html'),'utf8');
const hub=fs.readFileSync(path.join(root,'app/src/main/assets/location_hub.js'),'utf8');
const diag=fs.readFileSync(path.join(root,'app/src/main/assets/location_diagnostics.js'),'utf8');
const script=html.match(/<script>\s*'use strict';([\s\S]*?)<\/script>/);
assert(script,'App runtime script missing');
new vm.Script("'use strict';"+script[1]);
new vm.Script(hub);
new vm.Script(diag);
assert(java.includes('@JavascriptInterface public void requestAutoLocation()'),'No native auto location bridge');
assert(java.includes('if(autoLocationAttempted||isFinishing())return'),'Auto bridge not debounced');
assert(java.includes('beginLocation();'),'Need full fused+GNSS location workflow');
const auto=java.slice(java.indexOf('public void requestAutoLocation()'),java.indexOf('public void retryOfflineGpsWhenPermitted()'));
assert(auto.includes('beginLocation();'),'Auto must use Fused and GNSS');
assert(!auto.includes('startSatelliteOnly();'),'Auto cannot be GPS only');
const begin=java.slice(java.indexOf('private void beginLocation(){'),java.indexOf('private void startGoogleOrNetwork(){'));
assert(begin.indexOf('startGpsFallback();')<begin.indexOf('startGoogleOrNetwork();'),'Satellite + Google must start together');
assert(java.includes('isGoogleLocationAccuracyEnabled()'),'Google location accuracy must be diagnosed');
assert(java.includes('getFusedLocationProviderClient(this)'),'Fused location client missing');
assert(java.includes('requestLocationUpdates(updates,fusedCallback,Looper.getMainLooper())'),'Fused continuous request absent');
assert(java.includes('GPS_PROVIDER,2000L,0f,this'),'First GPS fix should work while stationary');
assert(java.includes('candidateCount')&&java.includes('rejectedCount')&&java.includes('lastCandidateStatus'));
assert(diag.includes('candidateText(status)')&&diag.includes('googleLocationAccuracyEnabled'));
const start=java.indexOf('private void sendLocationDiagnostics(){'),end=java.indexOf('private boolean hasFine(){',start);
assert(!java.slice(start,end).includes('getLatitude()')&&!java.slice(start,end).includes('getLongitude()'),'Coordinates must not appear in diagnostics');
const runtime=html.slice(html.indexOf('function init(){'),html.indexOf('init();\n</script>'));
assert(runtime.includes('requestAutoLocation();'),'App launch should start high accuracy acquisition');
assert(!runtime.includes('retryOfflineGpsWhenPermitted();'),'Old GPS-only startup must be removed');
assert(html.includes('id="nz-location-blue-dot"')&&html.includes('id="nz-location-live-dot"'));
assert(hub.includes("data-status")===false || hub.includes('dataset.status=state'));
assert(hub.includes("else{state='precise';message=live[0];}"),'Blue only on good fix');
assert(hub.includes("state='stale'")&&hub.includes("state='approx'")&&hub.includes("state='manual'"));
console.log('PASS v0.23: auto startup uses Google Fused plus GPS and network; blue dot requires live precise fix; diagnostic identifies rejected measurements.');
