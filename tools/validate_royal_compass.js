'use strict';
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const assets=path.join(root,'app/src/main/assets');
const html=fs.readFileSync(path.join(assets,'index.html'),'utf8');
const css=fs.readFileSync(path.join(assets,'learning_styles.css'),'utf8');
const frame=fs.readFileSync(path.join(assets,'compass_ornate_frame.svg'),'utf8');
const gradle=fs.readFileSync(path.join(root,'app/build.gradle'),'utf8');
assert(gradle.includes('versionCode 20')&&gradle.includes('0.19-offline-online-qibla-preview'));
assert((html.match(/id="needle"/g)||[]).length===1,'single needle container');
assert((html.match(/class="premium-needle"/g)||[]).length===1,'single animated arrow visual');
assert(html.includes('class="needle-wrap ornate-single-needle"'),'Single arrow class missing');
assert(html.includes('compass_ornate_frame.svg'),'Ornate frame asset missing');
assert(!html.includes('needleTeal'),'Old blue counterpoint must be removed');
assert(html.includes('id="pro-compass-heading"')&&html.includes('id="pro-compass-difference"'));
assert(html.includes('function updateNeedle(){')&&html.includes("trusted?wrap(bearing-h,360):0"),'Reliable native direction hook lost');
assert(css.includes('ornate-single-needle')&&css.includes('ornate-compass-frame')&&css.includes('max-width:759px'));
assert(frame.includes('viewBox="0 0 400 400"')&&frame.includes('id="raisedGold"'));
assert((frame.match(/<g transform="rotate\(/g)||[]).length===28,'24 emboss reliefs + 4 cardinal ornaments expected');
assert((frame.match(/<line /g)||[]).length===120,'Degree marks lost');
assert(frame.length>35000&&frame.length<150000);
assert(!html.includes('adhan_settings.js'),'Ezan settings unexpectedly returned');
console.log('PASS v0.14: single gold arrow, 24 embossed ornaments, 120 ticks, offline SVG, 12-language readout, old sensors preserved.');
