'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert'),vm=require('node:vm');
const root=path.resolve(__dirname,'../app/src/main/assets');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sun=fs.readFileSync(path.join(root,'sun_qibla.js'),'utf8');
const native=fs.readFileSync(path.resolve(root,'../java/com/geminamaz/app/MainActivity.java'),'utf8');
const env={window:{}};vm.runInNewContext(sun,env);
const sp=env.window.NamazSunQibla;
const near=(a,b,tol)=>Math.abs(a-b)<tol;
const equinoxRise=sp.position(new Date('2026-03-20T06:00:00Z'),0,0);
const equinoxNoon=sp.position(new Date('2026-03-20T12:00:00Z'),0,0);
const equinoxSet=sp.position(new Date('2026-03-20T18:00:00Z'),0,0);
assert(near(equinoxRise.azimuth,90,4),JSON.stringify(equinoxRise));
assert(near(equinoxSet.azimuth,270,4),JSON.stringify(equinoxSet));
assert(equinoxNoon.altitude>86);
const malaysia=sp.alignment(new Date('2026-11-07T07:00:00Z'),3.139,101.686,272.2);
assert(malaysia?.usable&&malaysia.altitude>7&&malaysia.altitude<78,JSON.stringify(malaysia));
assert(near(malaysia.shadowAzimuth,(malaysia.azimuth+180)%360,0.00001));
assert(near(malaysia.relative,(272.2-malaysia.shadowAzimuth+360)%360,0.0001));
const night=sp.alignment(new Date('2026-11-07T17:00:00Z'),3.139,101.686,272.2);
assert(!night.usable,'Night must not enable shadow');
const js=html.match(/<script>\s*'use strict';([\s\S]*?)<\/script>/);
assert(js,'Missing inline runtime');
new vm.Script("'use strict';"+js[1]);
assert(html.includes('window.GemiNative.requestAutoLocation();')&&html.includes('locationIsStale()'));
assert(html.includes("if(hasCached){")&&html.includes("state.manual=manualSaved"));
assert(html.includes('function locationFresh(')&&html.includes('function validLocation()'));
assert(html.includes('function shadowActive()')&&html.includes('function alignToShadow()'));
assert(html.includes('window.NamazSunQibla.alignment('));
assert(html.includes('locationIsStale()'));
assert(html.includes('const relative=fresh&&Number.isFinite(h)?wrap(bearing-h,360):bearing;'));
assert(html.includes("window.GemiNative.requestSatelliteLocation()"));
assert(html.includes("window.GemiNative.requestLocation()"));
assert(html.includes("document.addEventListener('visibilitychange'"));
assert(html.includes("if(byShadow&&needle)needle.style.transform='rotate('+shadowAlignment.relative+'deg)'"));
assert(native.includes('private void startSatelliteOnly()'));
assert(native.includes('@JavascriptInterface public void requestSatelliteLocation()'));
const finish=native.indexOf('@Override public void onPageFinished');
const end=native.indexOf('setContentView(webView)',finish);
assert(!native.slice(finish,end).includes('beginLocation()'),'Page load must not start Google positioning');
const resume=native.indexOf('@Override protected void onResume()');
const pause=native.indexOf('@Override protected void onPause()',resume);
assert(native.slice(resume,pause).includes('beginLocation()'),'Unfinished smart search should resume on wake');
console.log('PASS: solar sunrise/east sunset/west and daytime shadow math, nighttime disabled, runtime parses, cached data survives expiry, no auto Google on wake.');
