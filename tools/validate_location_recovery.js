'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'app/src/main/assets/index.html'),'utf8');
const native=fs.readFileSync(path.join(root,'app/src/main/java/com/geminamaz/app/MainActivity.java'),'utf8');
const inline=html.match(/<script>\s*'use strict';([\s\S]*?)<\/script>/);
assert(inline,'App script missing');
new vm.Script("'use strict';"+inline[1],{filename:'index-inline.js'});
assert(native.includes('private static final float LOCATION_MAX_ACCURACY_M = 20000f'));
const start=native.indexOf('private void beginLocation(){'),end=native.indexOf('private void startGoogleOrNetwork(){',start);
assert(start>0&&end>start);
const block=native.slice(start,end);
assert(block.indexOf('if(hasFine())startGpsFallback();')<block.indexOf('startGoogleOrNetwork();'),'GPS must start before Google and network');
assert(block.includes('handler.postDelayed(warningRunnable,60000L)'));
assert(native.includes('@JavascriptInterface public void requestPreciseLocation()'));
assert(native.includes('@JavascriptInterface public void openAppLocationPermissionSettings()'));
assert(native.includes('Manifest.permission.ACCESS_FINE_LOCATION,'));
assert(native.includes('Manifest.permission.ACCESS_COARSE_LOCATION},REQ_LOCATION'));
assert(html.includes('id="location-rescue"'));
assert(html.includes('id="location-app-settings-button"'));
assert(html.includes('id="location-precise-button"'));
assert(html.includes('id="location-manual-shortcut"'));
assert(html.includes('id="location-last-known"'));
assert(html.includes('id="manual-location-details"'));
assert(html.includes('function renderLocationRescue()'));
assert(html.includes('window.confirm(rescueWords()[6])'));
assert(html.includes("state.manual=true;"));
assert(!html.includes('adhan_settings.js'));
console.log('PASS: inline JavaScript parses; GPS starts with Google, coarse permission accepted, precise/settings/manual/last-known recovery wired.');
